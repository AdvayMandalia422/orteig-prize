// Builds assets/map-data.js: a pre-projected North Atlantic chart and
// Lindbergh's 1927 route, so the game needs no map library at runtime.
// Run: cd tools && npm install && node build-map.mjs
import { readFileSync, writeFileSync } from "fs";
import { geoMercator, geoPath, geoGraticule, geoDistance, geoInterpolate } from "d3-geo";
import { feature } from "topojson-client";

const W = 1000, H = 560;
const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-50m.json", "utf8"));
const land = feature(topo, topo.objects.land);

const bounds = { type: "MultiPoint", coordinates: [[-77, 37.2], [5, 57.5]] };
const projection = geoMercator().fitExtent([[24, 24], [W - 24, H - 24]], bounds);
projection.clipExtent([[0, 0], [W, H]]);
const path = geoPath(projection).digits(1);

// Lindbergh's route, May 20–21, 1927.
const STOPS = [
  { id: "ny", name: "Roosevelt Field", sub: "Long Island, New York", lon: -73.61, lat: 40.73 },
  { id: "capecod", name: "Cape Cod", sub: "Massachusetts", lon: -70.0, lat: 41.9 },
  { id: "novascotia", name: "Nova Scotia", sub: "Canada", lon: -64.6, lat: 44.6 },
  { id: "newfoundland", name: "St. John's", sub: "Newfoundland", lon: -52.71, lat: 47.56 },
  { id: "ireland", name: "Dingle Bay", sub: "Ireland", lon: -10.3, lat: 52.1 },
  { id: "england", name: "Plymouth", sub: "England", lon: -4.14, lat: 50.37 },
  { id: "cherbourg", name: "Cherbourg", sub: "France", lon: -1.62, lat: 49.64 },
  { id: "paris", name: "Le Bourget", sub: "Paris, France", lon: 2.44, lat: 48.97 },
];
const EARTH_MI = 3958.8;
let total = 0;
const segs = [];
for (let i = 1; i < STOPS.length; i++) {
  const a = [STOPS[i - 1].lon, STOPS[i - 1].lat], b = [STOPS[i].lon, STOPS[i].lat];
  const d = geoDistance(a, b) * EARTH_MI;
  segs.push({ a, b, d });
  total += d;
}
const scale = 3600 / total; // normalise to the game's 3,600-mile route
const route = [];
let acc = 0;
STOPS[0].mi = 0;
segs.forEach((s, i) => {
  const n = Math.max(4, Math.round(s.d / 40));
  const interp = geoInterpolate(s.a, s.b);
  for (let k = i === 0 ? 0 : 1; k <= n; k++) {
    const [x, y] = projection(interp(k / n));
    route.push([Math.round((acc + (s.d * k) / n) * scale * 10) / 10, Math.round(x * 10) / 10, Math.round(y * 10) / 10]);
  }
  acc += s.d;
  STOPS[i + 1].mi = Math.round(acc * scale);
});
const stops = STOPS.map((s) => {
  const [x, y] = projection([s.lon, s.lat]);
  return { id: s.id, name: s.name, sub: s.sub, mi: s.mi, x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 };
});
const label = (text, lon, lat, kind) => {
  const [x, y] = projection([lon, lat]);
  return { text, x: Math.round(x), y: Math.round(y), kind };
};
const labels = [
  label("NORTH ATLANTIC OCEAN", -36, 43.5, "sea"),
  label("NEWFOUNDLAND", -58.5, 51.6, "land"),
  label("NOVA SCOTIA", -61.6, 42.9, "land-sm"),
  label("UNITED STATES", -71.6, 45.2, "land"),
  label("IRELAND", -8.2, 53.3, "land-sm"),
  label("ENGLAND", -1.6, 52.6, "land-sm"),
  label("FRANCE", 2.6, 45.6, "land"),
];
const graticule = path(geoGraticule().step([10, 5]).extent([[-100, 30], [20, 65]])());
const data = { w: W, h: H, land: path(land), graticule, route, stops, labels };
writeFileSync("../assets/map-data.js", "/* Generated by tools/build-map.mjs from world-atlas land-50m (Natural Earth, public domain). */\nwindow.ORTEIG_MAP = " + JSON.stringify(data) + ";\n");
console.log("route miles total (raw):", Math.round(total), "stops:", stops.map((s) => s.id + "@" + s.mi).join(" "));
console.log("bytes:", JSON.stringify(data).length, "land path:", data.land.length);
